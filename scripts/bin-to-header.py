"""Convert a binary file into a C++17 header containing its bytes."""

import argparse
import os
import pathlib
import re
import sys
import tempfile


def sanitize_identifier(text: str) -> str:
    """Sanitize a string to be a valid C++ identifier."""
    ident = re.sub(r"\W", "_", text, flags=re.ASCII)
    if not ident or ident[0].isdigit():
        ident = "_" + ident
    return ident


def format_words(data: bytes, indent: str = "    ") -> str:
    """Format a bytes object as a C++ std::uint32_t array initializer."""
    words_per_line = 8
    words = [
        int.from_bytes(data[i: i + 4], "little") for i in range(0, len(data), 4)
    ]
    if not words:
        return f"{indent}0x00000000u"
    lines = []
    for i in range(0, len(words), words_per_line):
        chunk = words[i: i + words_per_line]
        lines.append(indent + ", ".join(f"0x{w:08x}u" for w in chunk))
    return ",\n".join(lines)


def generate(data: bytes, name: str, source_name: str) -> str:
    """Generate a C++ header from binary data."""
    out = []
    out.append(f"// Generated by bin-to-header.py from '{source_name}' - DO NOT EDIT.")
    out.append("#pragma once")
    out.append("")
    out.append("#include <cstdint>")
    out.append("#include <vector>")
    out.append("")

    out.append(f"static std::vector<uint32_t> {name} = {{")
    out.append(format_words(data))
    out.append("};")
    out.append("")

    return "\n".join(out)


def write_if_changed(path: pathlib.Path, content: str) -> bool:
    """Write content atomically; skip if identical. Returns True if written."""
    encoded = content.encode("utf-8")
    if path.is_file() and path.read_bytes() == encoded:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name, suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(encoded)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return True


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments."""
    p = argparse.ArgumentParser(
        description="Convert a binary file into a C++17 header (.hxx)."
    )
    p.add_argument("input", type=pathlib.Path, help="binary file to embed")
    p.add_argument("output", type=pathlib.Path, help="header file to generate")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Entry point for the script."""
    args = parse_args(argv)

    try:
        data = args.input.read_bytes()
    except OSError as e:
        print(f"bin-to-header: cannot read '{args.input}': {e}", file=sys.stderr)
        return 1

    content = generate(data, sanitize_identifier(args.input.name), args.input.name)

    try:
        write_if_changed(args.output, content)
    except OSError as e:
        print(f"bin-to-header: cannot write '{args.output}': {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
